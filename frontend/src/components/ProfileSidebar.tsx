"use client";

import Link from "next/link";
import { useState } from "react";
import { Building2, CalendarDays, Link2, MapPin, Users } from "lucide-react";

import { Avatar } from "@/components/Navbar";
import { SkillBadges } from "@/components/SkillBadges";
import { useAuth } from "@/context/AuthContext";
import type { SkillRead, UserProfile } from "@/lib/types";
import { formatDate, formatNumber } from "@/lib/utils";

interface Props {
  profile: UserProfile;
}

/**
 * Profile sidebar — the GitHub-style identity card.
 *
 * Avatar, display name, bio, location/company/website, follower counters and
 * the AI-generated skill badges.
 *
 * Ownership is derived from the auth context rather than a server-passed prop,
 * so the same server-rendered profile page lights up correctly the moment the
 * client hydrates the signed-in user.
 */
export function ProfileSidebar({ profile }: Props) {
  const { user } = useAuth();
  const isOwner = user?.username === profile.username;

  // Skills can be re-generated by the owner; keep them in local state so a
  // refresh updates the badges without a full page reload.
  const [skills, setSkills] = useState<SkillRead[]>(profile.skills);

  return (
    <aside className="space-y-4">
      <div className="flex items-start gap-3">
        <Avatar user={profile} size={72} className="ring-2 ring-canvas" />
        <div className="min-w-0 pt-1">
          <h1 className="truncate text-xl font-semibold leading-tight">
            {profile.display_name ?? profile.username}
          </h1>
          <p className="truncate text-sm text-fg-muted">@{profile.username}</p>
        </div>
      </div>

      {profile.bio && <p className="text-sm leading-relaxed text-fg">{profile.bio}</p>}

      <div className="space-y-1.5 text-sm text-fg-muted">
        {profile.company && (
          <p className="flex items-center gap-2">
            <Building2 className="h-3.5 w-3.5 shrink-0" />
            <span className="truncate">{profile.company}</span>
          </p>
        )}
        {profile.location && (
          <p className="flex items-center gap-2">
            <MapPin className="h-3.5 w-3.5 shrink-0" />
            <span className="truncate">{profile.location}</span>
          </p>
        )}
        {profile.website && (
          <p className="flex items-center gap-2">
            <Link2 className="h-3.5 w-3.5 shrink-0" />
            <a
              href={profile.website.startsWith("http") ? profile.website : `https://${profile.website}`}
              target="_blank"
              rel="noreferrer noopener"
              className="link truncate"
            >
              {profile.website.replace(/^https?:\/\//, "")}
            </a>
          </p>
        )}
        <p className="flex items-center gap-2">
          <Users className="h-3.5 w-3.5 shrink-0" />
          <span>
            <strong className="font-semibold text-fg">{formatNumber(profile.followers_count)}</strong>{" "}
            followers ·{" "}
            <strong className="font-semibold text-fg">{formatNumber(profile.following_count)}</strong>{" "}
            following
          </span>
        </p>
        <p className="flex items-center gap-2">
          <CalendarDays className="h-3.5 w-3.5 shrink-0" />
          <span>Joined {formatDate(profile.created_at)}</span>
        </p>
      </div>

      <div className="grid grid-cols-3 gap-2 border-y border-border py-3 text-center">
        <Stat label="Repos" value={profile.total_repos} href={`/${profile.username}?tab=repositories`} />
        <Stat label="Commits" value={profile.total_commits} />
        <Stat label="Stars" value={profile.total_stars} />
      </div>

      {isOwner && (
        <Link href="/dashboard" className="btn w-full justify-center text-xs">
          Open dashboard
        </Link>
      )}

      <SkillBadges skills={skills} canRefresh={isOwner} onRefresh={setSkills} />
    </aside>
  );
}

function Stat({ label, value, href }: { label: string; value: number; href?: string }) {
  const content = (
    <>
      <p className="text-base font-semibold leading-tight">{formatNumber(value)}</p>
      <p className="text-2xs uppercase tracking-wide text-fg-muted">{label}</p>
    </>
  );

  return href ? (
    <Link href={href} className="rounded-md py-1 transition hover:bg-canvas-subtle">
      {content}
    </Link>
  ) : (
    <div className="rounded-md py-1">{content}</div>
  );
}
